    // --- stream: real Readable/Writable/Duplex/Transform/PassThrough.
    // Node's `require('stream')` returns the Stream constructor itself
    // with Readable/Writable/etc as static properties. We implement a
    // synchronous-ish subset: `write(chunk)` runs `_write(chunk, enc, cb)`
